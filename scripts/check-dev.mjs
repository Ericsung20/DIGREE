import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {asSql} from '../supabase/import-uw-catalog.mjs';
const require = createRequire(new URL('../apps/web/package.json', import.meta.url));
const {createClient} = require('@supabase/supabase-js');
const env = JSON.parse((await readFile(new URL('../supabase/.temp/dev-test-env.json', import.meta.url), 'utf8')).replace(/^\uFEFF/, ''));
const target = new URL(env.API_URL);
assert(['127.0.0.1', 'localhost'].includes(target.hostname) && target.port === '55321', 'Local dev only');
const make = key => createClient(env.API_URL, key, {auth: {persistSession: false, autoRefreshToken: false}});
const admin = make(env.SERVICE_ROLE_KEY);
const owner = make(env.ANON_KEY);
const other = make(env.ANON_KEY);
const run = randomUUID();
const ids = [];
const courseId = `qa-${run}`;
const term = `QA-${run}`;
const college = randomUUID();
const program = randomUUID();
let checks = 0;
const ok = name => { checks++; console.log(`PASS ${name}`); };
const data = result => { if (result.error) throw result.error; return result.data; };
try {
  const sql = asSql({term: {id: term, label: 'Integration test'},
    courses: [{id: courseId, code: 'QA 987', title: 'Integration course', credit_options: [3], breadth: ['S'], repeatable: false, source: 'test', fetched_at: new Date().toISOString()}],
    packages: [{term, course_id: courseId, bundle_id: 'qa-A', seat_status: 'open', section_label: 'LEC 001', instructors: ['QA Instructor'], meetings: []}], stats: [], buildings: []});
  const imported = spawnSync('docker', ['exec', '-i', 'supabase_db_DIGREE-dev', 'psql', '-X', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], {input: sql, encoding: 'utf8'});
  assert.equal(imported.status, 0, imported.stderr);
  assert.equal(data(await admin.from('course_offerings').select('credit_options').eq('course_id', courseId).single()).credit_options[0], 3);
  assert.deepEqual(data(await admin.from('course_instructors').select('instructors').eq('course_id', courseId).single()).instructors, ['QA Instructor']);
  data(await admin.from('courses').update({credit_options: [4]}).eq('id', courseId));
  assert.equal(data(await admin.from('course_offerings').select('credit_options').eq('course_id', courseId).single()).credit_options[0], 3);
  ok('import writes provenance, authoritative instructors and immutable term credits');
  data(await admin.from('course_requisites').insert({term, course_id: courseId, course_aliases: ['QA 987', 'MATH 987'], source_url: 'test', fetched_at: new Date().toISOString()}));
  for (const client of [owner, other]) {
    const email = `qa-${ids.length}-${run}@wisc.edu`;
    const password = `Qatest!${randomUUID()}`;
    const created = data(await admin.auth.admin.createUser({email, password, email_confirm: true})).user;
    ids.push(created.id);
    data(await client.auth.signInWithPassword({email, password}));
  }
  const first = data(await owner.rpc('search_catalog_courses', {p_query: 'QA 987'}));
  const second = data(await owner.rpc('search_catalog_courses', {p_query: 'MATH 987'}));
  assert.equal(first[0].id, courseId); assert.equal(second[0].id, courseId);
  assert.equal(first[0].display_code, 'QA/MATH 987');
  ok('PostgREST alias search yields one canonical course and combined label');
  data(await admin.from('colleges').insert({id: college, label: `QA college ${run}`}));
  data(await admin.from('academic_programs').insert({id: program, college_id: college, label: 'QA Degree, BS', catalog_year: 2026}));
  data(await admin.from('program_requirement_catalog').insert({program_id: program, source_url: 'https://guide.wisc.edu/qa', extraction_method: 'guide_html', fetched_at: new Date().toISOString(), course_groups: [{heading: 'College Degree Requirements', rows: [{kind: 'criterion', label: 'Total Credits', credit_conditions: ['120 credits']}]}, {heading: 'Basic courses', rows: [{kind: 'course', courses: [{code: 'MATH 987'}], credits: '3'}]}]}));
  data(await owner.from('academic_profiles').insert({user_id: ids[0], college_id: college, program_id: program, catalog_year: 2026}));
  const selections = data(await owner.from('student_programs').select('*'));
  assert.equal(selections[0].program_id, program);
  assert.equal(data(await other.from('student_programs').select('*')).length, 0);
  assert.equal(data(await owner.from('requirement_groups').select('*').eq('program_version_id', `major:${program}`)).length, 2);
  ok('program import populates normalized requirements and owner-filtered selection');
  const transfer = data(await owner.from('transfer_credits').insert({institution: 'QA School', source_course: 'MAT 987', equivalent_course_id: courseId, credits: 3, awarded_term: '2027SP'}).select().single());
  assert.equal(data(await owner.from('transfer_credits').select('equivalent_course_id, awarded_term, courses(code)'))[0].courses.code, 'QA 987');
  assert.equal(data(await other.from('transfer_credits').select('*')).length, 0);
  assert.equal(data(await owner.rpc('my_chat_rooms')).length, 0);
  assert.equal(data(await owner.from('grade_entries').select('*')).length, 0);
  const spoof = await other.from('transfer_credits').insert({user_id: ids[0], institution: 'Bad', source_course: 'Bad', credits: 3, awarded_term: '2027SP'});
  assert(spoof.error);
  data(await owner.from('transfer_credits').update({credits: 2.5}).eq('id', transfer.id));
  assert.equal(Number(data(await owner.from('transfer_credits').select('credits').single()).credits), 2.5);
  ok('transfer CRUD respects ownership, course relations, GPA and chat boundaries');
  data(await owner.from('planner_courses').insert({user_id: ids[0], term, course_id: courseId, credits: 3, status: 'planned'}));
  assert.equal(data(await owner.from('planner_courses').select('course_id, courses(code)'))[0].courses.code, 'QA 987');
  assert.equal(data(await owner.from('course_attempts').select('*')).length, 0);
  ok('planning and history views expose usable PostgREST relationships');
  const item = [{course_id: courseId, bundle_id: 'qa-A', credits: 3}];
  const saved = data(await owner.rpc('save_schedule', {p_term: term, p_items: item, p_request_id: 'first'}));
  const invalid = await owner.rpc('save_schedule', {p_term: term, p_items: [{...item[0], bundle_id: 'wrong'}], p_request_id: 'invalid'});
  assert(invalid.error);
  assert.equal(data(await owner.from('saved_schedules').select('id').eq('term', term).eq('state', 'active').single()).id, saved);
  const concurrent = await Promise.all(['a', 'b'].map(p_request_id => owner.rpc('save_schedule', {p_term: term, p_items: item, p_request_id})));
  concurrent.forEach(data);
  assert.equal(data(await owner.from('saved_schedules').select('id').eq('term', term).eq('state', 'active')).length, 3);
  assert((await owner.rpc('save_schedule', {p_term: term, p_items: item, p_request_id: 'fourth'})).error);
  data(await owner.rpc('archive_schedule', {p_schedule_id: saved}));
  data(await owner.rpc('save_schedule', {p_term: term, p_items: item, p_request_id: 'replacement'}));
  assert.equal(data(await owner.from('saved_schedules').select('id').eq('term', term).eq('state', 'active')).length, 3);
  ok('concurrent saves enforce three plan slots and allow replacement after deletion');
  data(await owner.from('friendships').insert({requester_id: ids[0], receiver_id: ids[1], status: 'pending'}));
  assert.equal(data(await other.from('saved_schedules').select('*')).length, 0);
  data(await other.from('friendships').update({status: 'accepted'}).eq('requester_id', ids[0]));
  assert.equal(data(await other.rpc('schedule_visibility', {owner: ids[0], viewer: ids[1]})), 'full');
  assert.equal(data(await other.from('transfer_credits').select('*')).length, 0);
  data(await other.from('user_blocks').insert({blocked_id: ids[0]}));
  assert.equal(data(await other.rpc('schedule_visibility', {owner: ids[0], viewer: ids[1]})), 'private');
  ok('friend acceptance shares schedules while blocks revoke access and transfers stay private');
  const signupEmail = `qa-signup-${run}@wisc.edu`;
  const signups = await Promise.all([make(env.ANON_KEY), make(env.ANON_KEY)].map(client => client.auth.signUp({email: signupEmail, password: `Qa!${run}`})));
  for (const signup of signups) if (signup.data.user?.id && !ids.includes(signup.data.user.id)) ids.push(signup.data.user.id);
  const users = data(await admin.auth.admin.listUsers({page: 1, perPage: 1000})).users.filter(user => user.email?.toLowerCase() === signupEmail);
  assert.equal(users.length, 1);
  if (!ids.includes(users[0].id)) ids.push(users[0].id);
  const again = await make(env.ANON_KEY).auth.signUp({email: signupEmail.toUpperCase(), password: `Qa!${run}`});
  assert(again.error || again.data.user?.identities?.length === 0);
  ok('simultaneous and mixed-case signup creates only one account');
  console.log(`${checks} live integration scenarios passed`);
} finally {
  for (const id of ids) await admin.auth.admin.deleteUser(id);
  await admin.from('requirement_groups').delete().eq('program_version_id', `major:${program}`);
  await admin.from('program_versions').delete().eq('id', `major:${program}`);
  await admin.from('program_requirement_catalog').delete().eq('program_id', program);
  await admin.from('academic_programs').delete().eq('id', program);
  await admin.from('colleges').delete().eq('id', college);
  await admin.from('chat_rooms').delete().eq('term', term);
  await admin.from('course_offerings').delete().eq('course_id', courseId);
  await admin.from('course_requisites').delete().eq('course_id', courseId);
  await admin.from('course_instructors').delete().eq('course_id', courseId);
  await admin.from('section_bundles').delete().eq('course_id', courseId);
  await admin.from('courses').delete().eq('id', courseId);
  await admin.from('terms').delete().eq('id', term);
}
